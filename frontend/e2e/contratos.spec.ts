import { savePrintPreview } from './print-helpers';
import { test, expect } from '@playwright/test';
import type { Page } from '@playwright/test';
async function login(page: Page, reader = false) {
  await page.goto('/clientes/app/contratos');
  await page.getByLabel('Usuário', { exact: true }).fill((reader ? process.env.E2E_READER_USERNAME : process.env.E2E_USERNAME)!);
  await page.getByLabel('Senha', { exact: true }).fill(process.env.E2E_PASSWORD!);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page.getByRole('heading', { name: /^Contratos/ })).toBeVisible();
}
async function date(page: Page, label: string, value: string) {
  await page.getByLabel(label, { exact: true }).fill(value);
  await page.getByLabel(label, { exact: true }).press('Enter');
}
test('contratos: itens, renovação, cálculo, edição, notas, relatório, impressão, empresa e exclusão', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await login(page);
  await expect(page.getByRole('button', { name: 'BETA', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Novo contrato', exact: true }).click();
  await page.getByLabel('Cliente', { exact: true }).click();
  await page.locator('.ant-select-dropdown:visible').getByText('Cliente Alfa', { exact: true }).click();
  await page.getByLabel('Número do contrato', { exact: true }).fill('CON-E2E');
  await date(page, 'Data do contrato', '01/01/2026');
  await date(page, 'Data final', '31/12/2026');
  await page.getByLabel('Objeto', { exact: true }).fill('Prestação de serviços de software.');
  await page.getByRole('button', { name: 'Adicionar produto ao contrato', exact: true }).click();
  await page.getByLabel('Produto 1', { exact: true }).click();
  await page.locator('.ant-select-dropdown:visible').getByText('Folha de pagamento', { exact: true }).click();
  await page.getByLabel('Valor do item 1', { exact: true }).fill('1000,12345');
  await page.getByLabel('Valor bruto', { exact: true }).fill('1000');
  await page.getByLabel('ISS (%)', { exact: true }).fill('5');
  await page.getByLabel('IRPJ (%)', { exact: true }).fill('1,5');
  const calculation = page.waitForResponse(r => r.url().endsWith('/calcular/') && r.status() === 200);
  await page.getByRole('button', { name: 'Calcular impostos', exact: true }).click();
  await calculation;
  await expect(page.getByLabel('Valor líquido', { exact: true })).toHaveValue(/935/);
  await page.getByRole('button', { name: 'Adicionar renovação', exact: true }).click();
  await date(page, 'Início da renovação 1', '01/01/2027');
  await date(page, 'Fim da renovação 1', '31/12/2027');
  await page.getByRole('button', { name: 'Salvar contrato', exact: true }).click();
  const row = page.getByRole('row').filter({ hasText: 'CON-E2E' });
  await expect(row).toContainText('935,00');
  await expect(page.getByRole('dialog', { name: 'Editar contrato', exact: true })).toBeHidden();
  await row.getByRole('button', { name: 'Editar contrato', exact: true }).click();
  await expect(page.getByLabel('Valor do item 1', { exact: true })).toHaveValue(/1000,12345/);
  await page.getByLabel('Número do contrato', { exact: true }).fill('CON-E2E-EDITADO');
  await date(page, 'Fim da renovação 1', '31/12/2028');
  await page.getByRole('button', { name: 'Salvar contrato', exact: true }).click();
  await expect(page.getByRole('button', { name: 'CON-E2E-EDITADO', exact: true })).toBeVisible();
  await expect(page.getByRole('dialog', { name: 'Editar contrato', exact: true })).toBeHidden();
  await page.getByRole('button', { name: 'CON-E2E-EDITADO', exact: true }).click();
  const detail = page.getByRole('dialog', { name: 'Detalhes do contrato', exact: true });
  await expect(detail).toContainText('31/12/2028');
  await expect(detail).toContainText('Folha de pagamento');
  await expect(detail).toContainText('1.000,12345');
  await page.evaluate(() => { window.print = () => { document.body.dataset.printed = 'yes'; }; });
  await detail.getByRole('button', { name: 'Imprimir contrato', exact: true }).click();
  await expect(page.locator('body')).toHaveAttribute('data-printed', 'yes');
  await page.emulateMedia({ media: 'print' });
  await expect(page.locator('.contract-printable')).toBeVisible();
  await expect(page.locator('.workspace')).toBeHidden();
  await savePrintPreview(page, 'contrato');
  await page.emulateMedia({ media: 'screen' });
  await detail.getByRole('button', { name: 'Fechar', exact: true }).click();
  await expect(detail).toBeHidden();
  await page.getByRole('row').filter({ hasText: 'COM-NOTA' }).getByRole('button', { name: 'Editar contrato', exact: true }).click();
  await expect(page.getByLabel('Cliente', { exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Cancelar', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Editar contrato', exact: true })).toBeHidden();
  await page.getByRole('button', { name: 'COM-NOTA', exact: true }).click();
  await expect(detail).toContainText('NF-TESTE');
  await detail.getByRole('button', { name: 'Fechar', exact: true }).click();
  await expect(detail).toBeHidden();
  await page.getByRole('row').filter({ hasText: 'COM-NOTA' }).getByRole('button', { name: 'Excluir contrato', exact: true }).click();
  await page.getByRole('button', { name: 'Excluir', exact: true }).click();
  await expect(page.getByText('Operação impedida: existem notas ou outros registros vinculados ao contrato.', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Relatório de contratos', exact: true }).click();
  await page.getByRole('button', { name: 'Gerar relatório', exact: true }).click();
  await expect(page.getByRole('cell', { name: 'CON-E2E-EDITADO', exact: true })).toBeVisible();
  await expect(page.locator('.table-toolbar').getByText(/Total líquido:.*1.035,00/)).toBeVisible();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Exportar CSV' }).click();
  expect((await download).suggestedFilename()).toBe('relatorio-contratos.csv');
  await page.getByRole('link', { name: 'Contratos', exact: true }).click();
  await page.getByRole('combobox', { name: 'Empresa ativa', exact: true }).click();
  await page.locator('.ant-select-dropdown:visible').getByText('Empresa Beta', { exact: true }).click();
  await expect(page.getByRole('button', { name: 'BETA', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'CON-E2E-EDITADO', exact: true })).toHaveCount(0);
  await page.getByRole('combobox', { name: 'Empresa ativa', exact: true }).click();
  await page.locator('.ant-select-dropdown:visible').getByText('Empresa Alfa', { exact: true }).click();
  await page.getByRole('row').filter({ hasText: 'CON-E2E-EDITADO' }).getByRole('button', { name: 'Excluir contrato', exact: true }).click();
  await page.getByRole('button', { name: 'Excluir', exact: true }).click();
  await expect(page.getByRole('button', { name: 'CON-E2E-EDITADO', exact: true })).toHaveCount(0);
  const dir = process.env.E2E_SCREENSHOT_DIR || '/tmp/gestao-contratos-e2e';
  await expect(page.locator('.ant-message-notice').last()).toBeHidden();
  await page.screenshot({ path: dir + '/contratos.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: dir + '/contratos-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});

test('contratos: consulta não expõe botões de alteração', async ({ page }) => {
  await login(page, true);
  await expect(page.getByRole('button', { name: 'COM-NOTA', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Novo contrato', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Editar contrato', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Excluir contrato', exact: true })).toHaveCount(0);
});
