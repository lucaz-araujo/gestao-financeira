import { test, expect } from '@playwright/test';
test('agenda: contato com e-mail e telefone, edição e exclusão',async({page})=>{
 await page.goto('/clientes/app/agenda');
 await page.getByLabel('Usuário',{exact:true}).fill(process.env.E2E_USERNAME!);
 await page.getByLabel('Senha',{exact:true}).fill(process.env.E2E_PASSWORD!);
 await page.getByRole('button',{name:'Entrar',exact:true}).click();
 await expect(page.getByRole('heading',{name:/Agenda de contatos/})).toBeVisible();
 await expect(page.getByRole('cell',{name:'Contato Beta',exact:true})).toHaveCount(0);
 await expect(page.getByRole('cell',{name:'Contato sem cliente',exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'Novo contato',exact:true}).click();
 await page.getByLabel('Cliente',{exact:true}).click();
 await page.locator('.ant-select-dropdown:visible').getByText('Cliente Alfa',{exact:true}).click();
 await page.getByLabel('Nome',{exact:true}).fill('Contato navegador');
 await page.getByRole('button',{name:'Adicionar e-mail',exact:true}).click();
 await page.getByLabel('E-mail',{exact:true}).fill('navegador@example.test');
 await page.getByRole('button',{name:'Adicionar telefone',exact:true}).click();
 await page.getByLabel('Telefone',{exact:true}).fill('85999992222');
 await page.getByRole('button',{name:'Salvar contato',exact:true}).click();
 await expect(page.getByRole('dialog',{name:'Cadastro de contato'})).toBeHidden();
 let row=page.getByRole('row').filter({hasText:'Contato navegador'});await expect(row).toBeVisible();
 await row.getByRole('button',{name:'Editar',exact:true}).click();
 await expect(page.getByLabel('Nome',{exact:true})).toHaveValue('Contato navegador');
 await expect(page.getByLabel('E-mail',{exact:true})).toHaveValue('navegador@example.test');
 await page.getByLabel('E-mail',{exact:true}).fill('editado@example.test');
 await page.getByRole('button',{name:'Salvar contato',exact:true}).click();
 await expect(page.getByRole('dialog',{name:'Cadastro de contato'})).toBeHidden();
 await row.getByRole('button',{name:'Ver',exact:true}).click();
 await expect(page.getByText('editado@example.test',{exact:true})).toBeVisible();
 await expect(page.getByText('85999992222',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:/^(Close|Fechar)$/}).click();
 await row.getByRole('button',{name:'Excluir',exact:true}).click();
 await page.getByRole('dialog').getByRole('button',{name:'Excluir',exact:true}).click();
 await expect(row).toHaveCount(0);
});
