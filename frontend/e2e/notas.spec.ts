import { savePrintPreview } from './print-helpers';
import { test, expect } from '@playwright/test';
import type { Page } from '@playwright/test';
async function login(page: Page, reader = false) {
  await page.goto('/clientes/app/notas');
  await page.getByLabel('Usuário', { exact: true }).fill((reader ? process.env.E2E_READER_USERNAME : process.env.E2E_USERNAME)!);
  await page.getByLabel('Senha', { exact: true }).fill(process.env.E2E_PASSWORD!);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page.getByRole('heading', { name: /^Notas fiscais/ })).toBeVisible();
}
async function confirm(page: Page, label: string, endpoint: string) {
  const response = page.waitForResponse(r => r.url().includes('/' + endpoint + '/') && r.request().method() === 'POST');
  await page.getByRole('button', { name: label, exact: true }).click();
  const confirmation = page.locator('.ant-popover:visible').filter({ hasText: label + '?' });
  await confirmation.getByRole('button', { name: 'Confirmar', exact: true }).click();
  expect((await response).ok()).toBe(true);
  await expect(confirmation).toBeHidden();
}
test('notas: CRUD, geração, emissão simulada, consulta, e-mail local, receita, cancelamento e relatório', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await login(page);
  await expect(page.getByText('BETA', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Novo rascunho', exact: true }).click();
  await page.getByLabel('Contrato', { exact: true }).click();
  await page.locator('.ant-select-dropdown:visible').getByText('CON-ALFA — Cliente Alfa', { exact: true }).click();
  await page.getByLabel('Número para consulta (se existente)', { exact: true }).fill('MANUAL');
  await page.getByLabel('Discriminação dos serviços', { exact: true }).fill('Teste manual');
  await page.getByRole('button', { name: 'Salvar rascunho', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeHidden();
  const manual = page.getByRole('row').filter({ hasText: 'MANUAL' });
  await expect(manual).toBeVisible();
  await manual.getByRole('button', { name: 'Editar rascunho' }).click();
  const editor = page.getByRole('dialog', { name: 'Editar rascunho', exact: true });
  await expect(editor).toBeVisible();
  await expect(editor.getByLabel('Discriminação dos serviços', { exact: true })).toHaveValue('Teste manual');
  await editor.getByLabel('Discriminação dos serviços', { exact: true }).fill('Teste editado');
  const update = page.waitForResponse(response => response.url().includes('/notas/api/notas/') && response.request().method() === 'PATCH');
  await editor.getByRole('button', { name: 'Salvar rascunho', exact: true }).click();
  const updated = await update;
  expect(updated.ok()).toBe(true);
  expect((await updated.json()).texto_nota).toBe('Teste editado');
  await expect(page.getByRole('dialog', { name: 'Editar rascunho', exact: true })).toBeHidden();
  await manual.getByRole('button', { name: 'Excluir rascunho' }).click();
  await page.getByRole('button', { name: 'Excluir', exact: true }).click();
  await expect(manual).toHaveCount(0);
  await page.getByRole('button', { name: 'Gerar por contratos', exact: true }).click();
  await page.getByLabel('Contrato 1', { exact: true }).click();
  await page.locator('.ant-select-dropdown:visible').getByText('CON-ALFA — Cliente Alfa', { exact: true }).click();
  await page.getByLabel('Mês da competência', { exact: true }).fill('12');
  await page.getByRole('button', { name: 'Gerar rascunhos', exact: true }).click();
  const draft = page.getByRole('row').filter({ hasText: 'Rascunho #' });
  await expect(draft).toContainText('100,00');
  await draft.getByRole('button', { name: 'Ver nota' }).click();
  const detail = page.getByRole('dialog', { name: 'Detalhes da nota', exact: true });
  await expect(detail).toContainText('RASCUNHO — SEM VALIDADE FISCAL');
  await confirm(page, 'Emitir NFS-e', 'emitir');
  await expect(detail.getByRole('button', { name: 'Emitir NFS-e', exact: true })).toBeDisabled();
  await confirm(page, 'Consultar nota', 'consultar');
  await expect(detail).toContainText('TESTE-LOCAL');
  await expect(detail).toContainText('Autorizada');
  await confirm(page, 'Enviar por e-mail', 'email');
  await expect(detail).toContainText('O servidor de e-mail aceitou');
  await confirm(page, 'Gerar financeiro', 'financeiro');
  await expect(detail).toContainText('Sim');
  await expect(detail.getByRole('button', { name: 'Cancelar NFS-e', exact: true })).toBeDisabled();
  await detail.getByRole('button', { name: 'Obter link de consulta', exact: true }).click();
  await expect(detail.getByRole('link', { name: 'Abrir nota em nova aba' })).toHaveAttribute('href', /\/notas\/publica\//);
  await page.evaluate(() => { window.print = () => { document.body.dataset.printed = 'yes'; }; });
  await detail.getByRole('button', { name: 'Imprimir nota', exact: true }).click();
  await expect(page.locator('body')).toHaveAttribute('data-printed', 'yes');
  await page.emulateMedia({ media: 'print' });
  await expect(page.locator('.contract-printable')).toBeVisible();
  await expect(page.locator('.workspace')).toBeHidden();
  await savePrintPreview(page, 'nota-interna');
  const publicHref = await detail.getByRole('link', { name: 'Abrir nota em nova aba', exact: true }).getAttribute('href');
  const publicPage = await page.context().newPage();
  await publicPage.goto(new URL(publicHref!, page.url()).pathname);
  await savePrintPreview(publicPage, 'nota-publica');
  await publicPage.close();
  await page.emulateMedia({ media: 'screen' });
  await detail.getByRole('button', { name: 'Fechar', exact: true }).click();
  await expect(detail).toBeHidden();
  await page.getByRole('row').filter({ hasText: '9000' }).getByRole('button', { name: 'Ver nota' }).click();
  await detail.getByRole('button', { name: 'Cancelar NFS-e', exact: true }).click();
  await page.getByLabel('Justificativa', { exact: true }).fill('Cancelamento simulado de teste');
  await page.getByRole('button', { name: 'Confirmar cancelamento', exact: true }).click();
  await expect(detail).toContainText('Cancelada');
  await detail.getByRole('button', { name: 'Imprimir nota', exact: true }).click();
  await savePrintPreview(page, 'nota-cancelada');
  await detail.getByRole('button', { name: 'Fechar', exact: true }).click();
  await expect(detail).toBeHidden();
  await page.getByRole('link', { name: 'Relatório de notas', exact: true }).click();
  await page.getByRole('button', { name: 'Gerar relatório', exact: true }).click();
  await expect(page.getByRole('cell', { name: '9000', exact: true })).toBeVisible();
  await expect(page.locator('.table-toolbar').getByText(/Total líquido:.*200,00/)).toBeVisible();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Exportar CSV' }).click();
  expect((await download).suggestedFilename()).toBe('relatorio-notas.csv');
  await page.getByRole('link', { name: 'Notas fiscais', exact: true }).click();
  await page.getByRole('combobox', { name: 'Empresa ativa', exact: true }).click();
  await page.locator('.ant-select-dropdown:visible').getByText('Empresa Beta', { exact: true }).click();
  await expect(page.getByRole('button', { name: 'BETA', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: '9000', exact: true })).toHaveCount(0);
  await page.getByRole('combobox', { name: 'Empresa ativa', exact: true }).click();
  await page.locator('.ant-select-dropdown:visible').getByText('Empresa Alfa', { exact: true }).click();
  await expect(page.getByRole('button', { name: '9000', exact: true })).toBeVisible();
  await page.screenshot({ path: process.env.E2E_SCREENSHOT_DIR + '/notas.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: process.env.E2E_SCREENSHOT_DIR + '/notas-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
test('notas: leitor não pode alterar ou transmitir', async ({ page }) => {
  await login(page, true);
  await expect(page.getByRole('button', { name: 'Novo rascunho', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Editar rascunho', exact: true })).toHaveCount(0);
  await page.getByRole('row').filter({ hasText: '9000' }).getByRole('button', { name: 'Ver nota' }).click();
  await expect(page.getByRole('button', { name: 'Emitir NFS-e', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Cancelar NFS-e', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Gerar financeiro', exact: true })).toHaveCount(0);
});
